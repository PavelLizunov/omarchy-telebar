const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { loadLogic } = require('./qml-logic');
const root = path.resolve(__dirname, '..');
const quickText = fs.readFileSync(path.join(root, 'shell/TelebarQuickView.qml'), 'utf8');
function body(name) {
  const start = quickText.indexOf('  function ' + name + '(');
  assert(start >= 0);
  const end = quickText.indexOf('\n  }', start);
  return quickText.slice(start, end + 4);
}
let pending, commands = [];
const quick = { mediaOpenSerial: 0, shownChatId: 101, activeAccount: "default", viewingId: 0, viewingBlock: null, viewingFileId: 0,
  playing: { fileId: 81 }, status: '', focusItem: null, focusReturned() {},
  service: { request(cmd, args, cb) { commands.push(cmd); pending = cb; } } };
const scope = vm.createContext({ quick, Qt: { callLater(fn) { fn(); } } });
vm.runInContext(body('openMedia') + '\n' + body('closeMedia'), scope);
const note = { id: 701, chatId: 101, content: { kind: 'videoNote', media: { file: { id: 71, path: '/original/note.mp4' } } } };
scope.openMedia(note);
assert.equal(quick.viewingId, 0, 'Wait for previous playback to stop, not concurrent audio');
assert.equal(commands.at(-1), 'media.stop');
pending({ ok: true });
assert.equal(quick.viewingId, 701);
assert.equal(quick.viewingFileId, 71);
assert.equal(quick.viewingBlock, note);
scope.closeMedia();
assert.equal(quick.viewingId, 0);
scope.openMedia(note);
const old = pending;
scope.closeMedia();
old({ ok: true });
assert.equal(quick.viewingId, 0, 'Late stop answer cannot reopen a dismissed viewer');
scope.openMedia(note);
pending({ ok: false, error: 'Synthetic playback stop refused' });
assert.equal(quick.viewingId, 0);
assert.equal(quick.status, 'Synthetic playback stop refused');
scope.openMedia(note);
const oldChat = pending;
quick.shownChatId = 102;
oldChat({ ok: true });
assert.equal(quick.viewingId, 0, "Late stop answer cannot open media from a departed chat");
const beforeWrongChat = commands.length;
scope.openMedia(note);
assert.equal(commands.length, beforeWrongChat, "Retained wrong-chat row starts no operation");
quick.mediaOpenSerial++; quick.shownChatId = 101;
scope.openMedia(note);
const departed = pending;
quick.shownChatId = 102; quick.mediaOpenSerial++;
quick.shownChatId = 101; quick.mediaOpenSerial++;
departed({ ok: true });
assert.equal(quick.viewingId, 0, "A-to-B-to-A cancels old request");
quick.playing = { fileId: 0 };
scope.openMedia(note);
assert.equal(quick.viewingId, 0, "Zero observed playing state still needs pending-play retirement");
assert.equal(commands.at(-1), "media.stop");
pending({ ok: true });
assert.equal(quick.viewingId, 701);
assert(!commands.includes('file.open'), 'Round video must not use an external player');
for (const name of ['reset', 'leave']) assert(body(name).includes('quick.mediaOpenSerial++'));
const navigation = loadLogic('MainNavigation');
const window = {};
navigation.openPhoto({ omagram: window }, note);
assert.equal(window.viewerBlock, note);
assert.equal(window.viewerMessageId, 701);
assert.equal(window.viewerFileId, 71);
assert(quickText.includes("onShownChatIdChanged: { quick.mediaOpenSerial++"));
const main = fs.readFileSync(path.join(root, 'app/Main.qml'), 'utf8');
const media = fs.readFileSync(path.join(root, 'shell/MediaWindow.qml'), 'utf8');
for (const text of [main, media]) assert(text.includes('sourceComponent: RoundVideoViewer {'));
assert(main.includes('app: omagram') && main.includes('message: omagram.viewerBlock'));
assert(media.includes('app: window.host') && media.includes('message: window.host.viewingBlock'));
const viewer = fs.readFileSync(path.join(root, 'app/RoundVideoViewer.qml'), 'utf8');
assert(viewer.includes('source: viewer.url') && viewer.includes('app.fileState(media.file)'));
assert(!viewer.includes('miniUrl') && !viewer.includes('file.open'));
assert(viewer.includes('radius: Style.cornerRadius') && viewer.includes('context.arc(width / 2, height / 2, width / 2'));
assert(viewer.includes('viewer.surfaceReady') && viewer.includes('function onFrameSwapped()'));
assert(!viewer.includes('MultiEffect') && !viewer.includes('layer.enabled'), 'Fullscreen video paints directly, without a hidden texture source');
console.log('Original round-video routes, one decoder/audio owner, stale/refused stop and native circle contracts passed');
